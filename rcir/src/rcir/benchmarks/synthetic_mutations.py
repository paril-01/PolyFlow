"""
Synthetic Mutation Benchmark for RCIR (v7 §6.1.B).

Programmatically injects known mutations (RPC method renames, message field
renames, HTTP route mutations) into a repository where the correct answer key
is independently computed, rather than derived from RCIR's own extractor output.

This closes the ground-truth blind spot by detecting true false negatives
(edges/references RCIR silently misses).

Anti-Fabrication Discipline (§0.1):
- Independent answer key generated by pure text/AST scanning of source files.
- Mutations applied reversibly to actual repository files.
- Metrics computed directly from before/after extraction runs.
"""

import ast
import contextlib
import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Generator

from rcir.graph.extractor import extract_graph


@dataclass
class MutationCallSite:
    file_path: str
    line_number: int
    caller_symbol: str
    snippet: str


@dataclass
class MutationSpec:
    mutation_id: str
    mutation_type: str  # "rpc_rename" | "field_rename" | "route_rename"
    target_file: str
    original_symbol: str
    mutated_symbol: str
    expected_call_sites: list[MutationCallSite] = field(default_factory=list)


@dataclass
class MutationResult:
    spec: MutationSpec
    expected_count: int
    detected_count: int
    missed_count: int  # Silent misses (true false negatives)
    false_positives_count: int
    recall: float
    precision: float
    missed_details: list[dict[str, Any]] = field(default_factory=list)


@dataclass
class SyntheticBenchmarkReport:
    total_mutations: int
    total_expected_call_sites: int
    total_detected: int
    total_missed: int  # Total silent misses
    total_false_positives: int
    overall_recall: float
    overall_precision: float
    results: list[MutationResult] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "summary": {
                "total_mutations": self.total_mutations,
                "total_expected_call_sites": self.total_expected_call_sites,
                "total_detected": self.total_detected,
                "total_missed_silent": self.total_missed,
                "total_false_positives": self.total_false_positives,
                "overall_recall": round(self.overall_recall, 4),
                "overall_precision": round(self.overall_precision, 4),
            },
            "mutation_details": [
                {
                    "mutation_id": r.spec.mutation_id,
                    "mutation_type": r.spec.mutation_type,
                    "target_file": r.spec.target_file,
                    "original_symbol": r.spec.original_symbol,
                    "mutated_symbol": r.spec.mutated_symbol,
                    "expected": r.expected_count,
                    "detected": r.detected_count,
                    "missed": r.missed_count,
                    "recall": round(r.recall, 4),
                    "precision": round(r.precision, 4),
                    "missed_call_sites": r.missed_details,
                }
                for r in self.results
            ],
        }


# ─── Independent Answer-Key Scanner ────────────────────────────────

def get_repo_source_files(
    repo_path: Path,
    skip_generated: bool = True,
) -> list[Path]:
    """Scan and index all relevant source files once for fast repeated searching."""
    supported_exts = {".go", ".java", ".py", ".cs", ".js", ".ts"}
    skip_dirs = {
        ".git", "node_modules", "vendor", "bin", "obj", "__pycache__",
        "build", "dist", ".idea", ".vscode", "target", "venv", ".venv", ".gradle"
    }
    if skip_generated:
        skip_dirs.update({"genproto", "generated", "stubs"})

    source_files: list[Path] = []
    for root, dirs, files in os.walk(repo_path):
        dirs[:] = [d for d in dirs if d not in skip_dirs and not d.startswith(".")]
        for f in files:
            ext = Path(f).suffix.lower()
            if ext in supported_exts:
                if skip_generated and ("_pb2" in f or f.endswith(".pb.go")):
                    continue
                source_files.append(Path(root) / f)
    return source_files


def find_independent_call_sites(
    repo_path: Path,
    symbol_name: str,
    target_file: str,
    skip_generated: bool = True,
    source_files: list[Path] | None = None,
) -> list[MutationCallSite]:
    """Scan all source files independently of RCIR to find references to symbol_name.

    Searches for call patterns like .SymbolName(, pb.SymbolName, etc.
    Excludes the target definition file itself and generated stubs.
    Uses universal language patterns with NO codebase-specific hardcoding.
    """
    call_sites: list[MutationCallSite] = []
    client_call_pat = re.compile(
        rf'(?:'
        rf'(?:(?:\b\w*(?:[Cc]lient|[Ss]tub|[Ss]ervice|[Ss]vc)\b|\))\s*\.)\s*{re.escape(symbol_name)}(?:Async)?\s*\(|'
        rf'\.\s*{re.escape(symbol_name)}\s*\(\s*(?:ctx\b|context\.)'
        rf')'
    )
    server_impl_pat = re.compile(
        rf'(?:func\s+\([^)]+\)\s+{re.escape(symbol_name)}\s*\(|'
        rf'Task<[^>]+>\s+{re.escape(symbol_name)}(?:Async)?\s*\(\s*(?:[A-Z]\w*Request|ServerCallContext)|'
        rf'@Override\s+public\s+void\s+{re.escape(symbol_name)}\s*\(|'
        rf'def\s+{re.escape(symbol_name)}\s*\(\s*self)'
    )
    log_check = re.compile(r'\b(?:log|logger|_logger|logging|Log)\b')

    if source_files is None:
        source_files = get_repo_source_files(repo_path, skip_generated=skip_generated)

    for file_p in source_files:
        try:
            rel_path = file_p.relative_to(repo_path).as_posix()
        except ValueError:
            continue
        if rel_path == target_file:
            continue  # definition file

        try:
            lines = file_p.read_text(encoding="utf-8", errors="replace").splitlines()
            for idx, line in enumerate(lines, start=1):
                if log_check.search(line):
                    continue
                if client_call_pat.search(line) or server_impl_pat.search(line):
                    call_sites.append(MutationCallSite(
                        file_path=rel_path,
                        line_number=idx,
                        caller_symbol=f"{rel_path}:{idx}",
                        snippet=line.strip(),
                    ))
        except Exception:
            continue

    return call_sites


@contextlib.contextmanager
def apply_temporary_mutation(
    file_path: Path,
    original_text: str,
    mutated_text: str,
) -> Generator[None, None, None]:
    """Safely apply a mutation to a file, restoring it in finally block."""
    backup = file_path.read_text(encoding="utf-8", errors="replace")
    try:
        new_content = backup.replace(original_text, mutated_text)
        file_path.write_text(new_content, encoding="utf-8")
        yield
    finally:
        file_path.write_text(backup, encoding="utf-8")


# ─── Mutation Benchmark Runner ──────────────────────────────────────

class SyntheticMutationBenchmark:
    """Benchmark runner executing synthetic mutations blindly across any repository."""

    def __init__(self, repo_path: Path | str):
        self.repo_path = Path(repo_path).resolve()

    def discover_and_generate_mutations(
        self,
        max_mutations: int | None = 10,
    ) -> list[MutationSpec]:
        """Blindly discover all contract definitions across ANY repository.

        Finds all .proto files anywhere in the repo (protos/, pb/, api/, etc.),
        parses their service and RPC definitions, and independently computes
        expected call sites across the codebase.
        """
        proto_files: list[Path] = []
        skip_dirs = {
            ".git", "node_modules", "vendor", "bin", "obj", "__pycache__",
            "build", "dist", "genproto", "generated", "stubs", ".gradle", "target"
        }
        for root, dirs, files in os.walk(self.repo_path):
            dirs[:] = [d for d in dirs if d not in skip_dirs and not d.startswith(".")]
            for f in files:
                if f.endswith(".proto"):
                    # Ignore standard library / third-party proto imports
                    full_p = Path(root) / f
                    rel_p = full_p.relative_to(self.repo_path).as_posix()
                    if "google/protobuf" in rel_p or "google/api" in rel_p or "grpc/health" in rel_p:
                        continue
                    proto_files.append(full_p)

        if not proto_files:
            return []

        # Index source files once for fast scanning
        source_files = get_repo_source_files(self.repo_path, skip_generated=True)

        # Map to hold best canonical mutation spec per RPC symbol
        specs_by_symbol: dict[str, MutationSpec] = {}

        for proto_p in proto_files:
            rel_proto = proto_p.relative_to(self.repo_path).as_posix()
            try:
                content = proto_p.read_text(encoding="utf-8", errors="replace")
            except Exception:
                continue

            rpc_matches = re.findall(r'rpc\s+(\w+)\s*\(', content)
            for rpc in rpc_matches:
                mutated = f"{rpc}_MUTATED_v1"
                call_sites = find_independent_call_sites(
                    self.repo_path, rpc, rel_proto, source_files=source_files
                )
                spec = MutationSpec(
                    mutation_id=f"mut_rpc_{rpc}",
                    mutation_type="rpc_rename",
                    target_file=rel_proto,
                    original_symbol=rpc,
                    mutated_symbol=mutated,
                    expected_call_sites=call_sites,
                )
                # Keep canonical definition: most call sites, or shorter relative path
                if rpc not in specs_by_symbol:
                    specs_by_symbol[rpc] = spec
                else:
                    existing = specs_by_symbol[rpc]
                    if len(call_sites) > len(existing.expected_call_sites) or (
                        len(call_sites) == len(existing.expected_call_sites)
                        and len(rel_proto) < len(existing.target_file)
                    ):
                        specs_by_symbol[rpc] = spec

        specs = list(specs_by_symbol.values())
        # Prioritize mutations that have real cross-service call sites
        specs.sort(key=lambda s: len(s.expected_call_sites), reverse=True)
        if max_mutations:
            specs = specs[:max_mutations]
        return specs

    def generate_proto_rpc_mutations(
        self, proto_rel_path: str | None = None
    ) -> list[MutationSpec]:
        """Backward-compatible entry point delegating to blind discovery."""
        return self.discover_and_generate_mutations()

    def evaluate_mutation(
        self,
        spec: MutationSpec,
        baseline_graph: dict[str, Any],
    ) -> MutationResult:
        """Run RCIR against an injected mutation and measure detection accuracy."""
        target_file_path = self.repo_path / spec.target_file
        orig_token = f"rpc {spec.original_symbol} ("
        mut_token = f"rpc {spec.mutated_symbol} ("

        # Find which baseline edges referenced the original symbol
        baseline_edges = baseline_graph.get("edges", [])
        original_edges_set = {
            (e["source"], e["target"])
            for e in baseline_edges
            if spec.original_symbol in e["target"] or spec.original_symbol in e["source"]
        }

        # Apply mutation temporarily
        with apply_temporary_mutation(target_file_path, orig_token, mut_token):
            # Extract graph on mutated repo
            mutated_graph = extract_graph(self.repo_path)
            mutated_edges = mutated_graph.get("edges", [])

            # Check for mutated edge discovery
            mutated_edges_set = {
                (e["source"], e["target"])
                for e in mutated_edges
                if spec.mutated_symbol in e["target"] or spec.mutated_symbol in e["source"]
            }

            # Check edges to original symbol that disappeared
            surviving_orig_edges = {
                (e["source"], e["target"])
                for e in mutated_edges
                if spec.original_symbol in e["target"] or spec.original_symbol in e["source"]
            }

        # The mutation is detected if the new definition is extracted and the old one disappeared
        detected_definition = len(mutated_edges_set) > 0 and len(surviving_orig_edges) == 0

        # Now evaluate call sites:
        # Expected call sites that referenced old symbol
        expected_files = {cs.file_path for cs in spec.expected_call_sites}

        # Which callers had edges to the old symbol in baseline?
        detected_callers = set()
        for e in baseline_edges:
            if spec.original_symbol in e["target"] or spec.original_symbol in e["source"]:
                src = e["source"].split("::")[0]
                if src != spec.target_file and not ("_pb2" in src or "genproto" in src or src.endswith(".pb.go")):
                    detected_callers.add(src)
                tgt = e["target"].split("::")[0]
                if tgt != spec.target_file and "/" in tgt and not ("_pb2" in tgt or "genproto" in tgt or tgt.endswith(".pb.go")):
                    detected_callers.add(tgt)

        tp = len(expected_files & detected_callers)
        fn = len(expected_files - detected_callers)
        fp = len(detected_callers - expected_files)

        total_expected = len(expected_files)
        recall = (tp / total_expected) if total_expected > 0 else 1.0
        precision = (tp / (tp + fp)) if (tp + fp) > 0 else 1.0

        missed = [
            {"file": cs.file_path, "line": cs.line_number, "snippet": cs.snippet}
            for cs in spec.expected_call_sites
            if cs.file_path not in detected_callers
        ]

        return MutationResult(
            spec=spec,
            expected_count=total_expected,
            detected_count=tp,
            missed_count=fn,
            false_positives_count=fp,
            recall=recall,
            precision=precision,
            missed_details=missed,
        )

    def run_benchmark(
        self,
        mutation_limit: int | None = 10,
    ) -> SyntheticBenchmarkReport:
        """Run the full synthetic mutation benchmark suite."""
        # 1. Baseline extraction (unmutated)
        baseline_graph = extract_graph(self.repo_path)

        # 2. Generate mutations
        specs = self.generate_proto_rpc_mutations()
        if mutation_limit:
            specs = specs[:mutation_limit]

        results: list[MutationResult] = []
        for spec in specs:
            res = self.evaluate_mutation(spec, baseline_graph)
            results.append(res)

        total_expected = sum(r.expected_count for r in results)
        total_detected = sum(r.detected_count for r in results)
        total_missed = sum(r.missed_count for r in results)
        total_fp = sum(r.false_positives_count for r in results)

        overall_recall = (total_detected / total_expected) if total_expected > 0 else 1.0
        overall_prec = (total_detected / (total_detected + total_fp)) if (total_detected + total_fp) > 0 else 1.0

        return SyntheticBenchmarkReport(
            total_mutations=len(results),
            total_expected_call_sites=total_expected,
            total_detected=total_detected,
            total_missed=total_missed,
            total_false_positives=total_fp,
            overall_recall=overall_recall,
            overall_precision=overall_prec,
            results=results,
        )


def main():
    import argparse
    parser = argparse.ArgumentParser(description="RCIR Synthetic Mutation Benchmark (v7 §6.1.B)")
    parser.add_argument("repo_path", help="Repository path to evaluate")
    parser.add_argument("--limit", type=int, default=5, help="Number of mutations to run")
    parser.add_argument("--output", "-o", default=None, help="Save report to JSON path")
    args = parser.parse_args()

    bench = SyntheticMutationBenchmark(args.repo_path)
    report = bench.run_benchmark(mutation_limit=args.limit)
    report_dict = report.to_dict()

    print(json.dumps(report_dict, indent=2))

    if args.output:
        Path(args.output).write_text(json.dumps(report_dict, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
