def validate_source_syntax(content: str, file_path: str) -> tuple[bool, str]:
    """Validate syntax of modified source code according to file extension."""
    ext = Path(file_path).suffix.lower()

    if ext == ".py":
        try:
            ast.parse(content)
            return True, "Python AST valid"
        except SyntaxError as e:
            return False, f"Python SyntaxError: {e}"

    elif ext in (".json",):
        try:
            json.loads(content)
            return True, "JSON syntax valid"
        except Exception as e:
            return False, f"JSON Error: {e}"

    elif ext in (".go", ".cs", ".java", ".proto"):
        # Brace matching & basic syntactic structure checks
        brace_count = content.count("{") - content.count("}")
        paren_count = content.count("(") - content.count(")")
        bracket_count = content.count("[") - content.count("]")
        if brace_count != 0:
            return False, f"Unbalanced braces in {file_path}: delta={brace_count}"
        if paren_count != 0:
            return False, f"Unbalanced parentheses in {file_path}: delta={paren_count}"
        if bracket_count != 0:
            return False, f"Unbalanced brackets in {file_path}: delta={bracket_count}"
        return True, f"{ext.lstrip('.').upper()} syntactic structure valid"

    return True, "Syntax check skipped (unsupported type)"


@contextlib.contextmanager
def apply_task_patch(
    repo_path: Path,
    mutations: dict[str, tuple[str, str]],
) -> Generator[dict[str, str], None, None]:
    """Reversibly apply sample mutations for a task, restoring on exit."""
    backups: dict[Path, str] = {}
    modified_contents: dict[str, str] = {}

    try:
        for rel_path, (orig_str, new_str) in mutations.items():
            full_p = repo_path / rel_path
            if full_p.exists():
                orig_content = full_p.read_text(encoding="utf-8", errors="replace")
                backups[full_p] = orig_content
                new_content = orig_content.replace(orig_str, new_str)
                full_p.write_text(new_content, encoding="utf-8")
                modified_contents[rel_path] = new_content
        yield modified_contents
    finally:
        for p, original in backups.items():
            p.write_text(original, encoding="utf-8")


class TaskSuccessHarness:
    """Benchmark harness evaluating task success with RCIR Context Contracts."""

    def __init__(self, repo_path: Path | str):
        self.repo_path = Path(repo_path).resolve()

    def evaluate_task(
        self,
        task: CrossServiceTask,
        graph: dict[str, Any] | None = None,
    ) -> TaskExecutionResult:
        """Evaluate a single cross-service task against RCIR graph extraction."""
        if graph is None:
            graph = extract_graph(self.repo_path)

        # 1. Generate Context Contract using Change Impact Report
        report = generate_change_impact_report(
            repo_path=self.repo_path,
            target_symbol=task.target_symbol,
            graph=graph,
        )

        # Gather files included in Context Contract
        contract_files_set: set[str] = set()
        for e in report.affected_edges:
            src_file = e.get("source", "").split("::")[0]
            if "/" in src_file or "\\" in src_file:
                contract_files_set.add(src_file.replace("\\", "/"))
            tgt_file = e.get("target", "").split("::")[0]
            if "/" in tgt_file or "\\" in tgt_file:
                contract_files_set.add(tgt_file.replace("\\", "/"))

        for unres in report.unresolved_locations:
            loc_file = unres.location.split("::")[0]
            if "/" in loc_file or "\\" in loc_file:
                contract_files_set.add(loc_file.replace("\\", "/"))

        # Normalize paths
        norm_contract_files = {f.replace("\\", "/") for f in contract_files_set}
        norm_expected_files = [f.replace("\\", "/") for f in task.expected_files]

        # Calculate contract coverage
        matched_files = [f for f in norm_expected_files if any(cf.endswith(f) or f.endswith(cf) for cf in norm_contract_files)]
        coverage = len(matched_files) / len(norm_expected_files) if norm_expected_files else 1.0
        contract_complete = (coverage >= 1.0)

        # 2. Test Patch Application & Syntax Validity
        syntax_valid = True
        patch_applied = False
        details = []

        if task.sample_mutations:
            with apply_task_patch(self.repo_path, task.sample_mutations) as modified:
                patch_applied = len(modified) > 0
                for rel_path, content in modified.items():
                    valid, msg = validate_source_syntax(content, rel_path)
                    if not valid:
                        syntax_valid = False
                        details.append(f"{rel_path}: {msg}")
                    else:
                        details.append(f"{rel_path}: {msg}")

        overall_success = contract_complete and patch_applied and syntax_valid

        return TaskExecutionResult(
            task_id=task.task_id,
            title=task.title,
            target_symbol=task.target_symbol,
            expected_files=norm_expected_files,
            contract_files=sorted(norm_contract_files),
            contract_coverage=coverage,
            contract_complete=contract_complete,
            patch_applied=patch_applied,
            syntax_valid=syntax_valid,
            overall_success=overall_success,
            details="; ".join(details) if details else "Contract evaluated",
        )

    def run_suite(
        self,
        tasks: list[CrossServiceTask] | None = None,
    ) -> TaskHarnessReport:
        """Run the task harness across all defined tasks."""
        if tasks is None:
            tasks = DynamicTaskSynthesizer(self.repo_path).synthesize_tasks()
            if not tasks:
                tasks = get_standard_online_boutique_tasks()

        # Extract baseline graph once for all tasks
        graph = extract_graph(self.repo_path)

        results: list[TaskExecutionResult] = []
        for t in tasks:
            res = self.evaluate_task(t, graph=graph)
            results.append(res)

        total = len(results)
        successful = sum(1 for r in results if r.overall_success)
        avg_coverage = (sum(r.contract_coverage for r in results) / total) if total > 0 else 1.0
        success_rate = (successful / total) if total > 0 else 1.0

        return TaskHarnessReport(
            total_tasks=total,
            successful_tasks=successful,
            contract_coverage_rate=avg_coverage,
            overall_success_rate=success_rate,
            results=results,
        )


def main():
    import argparse
    parser = argparse.ArgumentParser(description="RCIR End-to-End Task-Success Harness (v7 §6.2)")
    parser.add_argument("repo_path", help="Repository path to evaluate")
    parser.add_argument("--output", "-o", default=None, help="Output JSON path")
    args = parser.parse_args()

    harness = TaskSuccessHarness(args.repo_path)
    report = harness.run_suite()
    report_dict = report.to_dict()

    print(json.dumps(report_dict, indent=2))
    if args.output:
        Path(args.output).write_text(json.dumps(report_dict, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
