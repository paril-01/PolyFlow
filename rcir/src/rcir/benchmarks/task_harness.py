"""
End-to-End Task-Success Harness for RCIR (v7 §6.2, §7).

Measures whether RCIR's Context Contracts actually enable successful cross-service
refactoring tasks on a multi-service repository (Online Boutique).

Evaluates:
1. Context Contract Coverage: Did RCIR surface 100% of the cross-service call sites
   and definitions needed to complete the task?
2. Patch Application & Syntax Validity: Are the patches generated by an agent
   syntactically valid across all affected languages (Python AST, Go, C#, Java)?
3. End-to-End Task Success: Overall task success rate under live evaluation.

Anti-Fabrication Discipline (§0.1):
- All metrics computed from real graph queries and file AST validation.
- No mocked success rates or synthetic 100% hardcoded results.
"""

import ast
import contextlib
from dataclasses import dataclass, field
import json
import os
from pathlib import Path
from typing import Any, Callable, Generator

from rcir.graph.extractor import extract_graph
from rcir.impact import generate_change_impact_report


@dataclass
class CrossServiceTask:
    task_id: str
    title: str
    description: str
    target_symbol: str
    expected_files: list[str]
    prompt: str
    sample_mutations: dict[str, tuple[str, str]] = field(default_factory=dict)
    # sample_mutations: rel_path -> (original_snippet, replacement_snippet)


@dataclass
class TaskExecutionResult:
    task_id: str
    title: str
    target_symbol: str
    expected_files: list[str]
    contract_files: list[str]
    contract_coverage: float
    contract_complete: bool
    patch_applied: bool
    syntax_valid: bool
    overall_success: bool
    details: str = ""


@dataclass
class TaskHarnessReport:
    total_tasks: int
    successful_tasks: int
    contract_coverage_rate: float
    overall_success_rate: float
    results: list[TaskExecutionResult] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "summary": {
                "total_tasks": self.total_tasks,
                "successful_tasks": self.successful_tasks,
                "contract_coverage_rate": round(self.contract_coverage_rate, 4),
                "overall_success_rate": round(self.overall_success_rate, 4),
            },
            "tasks": [
                {
                    "task_id": r.task_id,
                    "title": r.title,
                    "target_symbol": r.target_symbol,
                    "expected_files": r.expected_files,
                    "contract_files": r.contract_files,
                    "contract_coverage": round(r.contract_coverage, 4),
                    "contract_complete": r.contract_complete,
                    "patch_applied": r.patch_applied,
                    "syntax_valid": r.syntax_valid,
                    "overall_success": r.overall_success,
                    "details": r.details,
                }
                for r in self.results
            ],
        }


class DynamicTaskSynthesizer:
    """Discovers multi-service contracts blindly and synthesizes cross-service tasks.

    Does NOT require hardcoded file paths, service names, or repo-specific rules.
    Blindly searches any repository for contracts (e.g. gRPC protobuf files),
    identifies real cross-service call sites across microservices, and synthesizes
    end-to-end refactoring tasks complete with sample mutations and expected files.
    """

    def __init__(self, repo_path: Path | str):
        self.repo_path = Path(repo_path).resolve()

    def _generate_file_mutation(self, rpc: str, snippet: str) -> tuple[str, str] | None:
        """Generate replacement tuple (original, replacement) from code snippet."""
        import re
        # C# server impl: Task<Type> Method( or Task Method(
        m = re.search(rf'(Task<[A-Za-z0-9_]+>\s+){re.escape(rpc)}(\s*\()', snippet)
        if m:
            return m.group(0), f"{m.group(1)}{rpc}V2{m.group(2)}"
        # Go server impl: func (...) Method(
        m = re.search(rf'(\)\s*){re.escape(rpc)}(\s*\()', snippet)
        if m:
            return m.group(0), f"{m.group(1)}{rpc}V2{m.group(2)}"
        # Java server impl: public void method(
        m = re.search(rf'(public\s+void\s+){re.escape(rpc)}(\s*\()', snippet)
        if m:
            return m.group(0), f"{m.group(1)}{rpc}V2{m.group(2)}"
        # Python server impl: def Method(
        m = re.search(rf'(def\s+){re.escape(rpc)}(\s*\()', snippet)
        if m:
            return m.group(0), f"{m.group(1)}{rpc}V2{m.group(2)}"
        # Client call: .Method( or .MethodAsync(
        m = re.search(rf'(\.\s*){re.escape(rpc)}((?:Async)?\s*\()', snippet)
        if m:
            async_suffix = "Async" if "Async" in m.group(2) else ""
            return m.group(0), f".{rpc}V2{async_suffix}("
        return None

    def synthesize_tasks(self, max_tasks: int = 5) -> list[CrossServiceTask]:
        """Synthesize up to max_tasks cross-service change tasks blindly."""
        import re
        from rcir.benchmarks.synthetic_mutations import (
            find_independent_call_sites,
            get_repo_source_files,
        )

        proto_files: list[Path] = []
        skip_dirs = {
            ".git", "node_modules", "vendor", "bin", "obj", "__pycache__",
            "build", "dist", "genproto", "generated", "stubs", ".gradle", "target"
        }
        for root, dirs, files in os.walk(self.repo_path):
            dirs[:] = [d for d in dirs if d not in skip_dirs and not d.startswith(".")]
            for f in files:
                if f.endswith(".proto"):
                    rel_p = (Path(root) / f).relative_to(self.repo_path).as_posix()
                    if "google/protobuf" in rel_p or "google/api" in rel_p or "grpc/health" in rel_p:
                        continue
                    proto_files.append(Path(root) / f)

        if not proto_files:
            return []

        source_files = get_repo_source_files(self.repo_path, skip_generated=True)

        tasks: list[CrossServiceTask] = []
        seen_rpcs: set[str] = set()

        for proto_p in proto_files:
            rel_proto = proto_p.relative_to(self.repo_path).as_posix()
            try:
                content = proto_p.read_text(encoding="utf-8", errors="replace")
            except Exception:
                continue

            service_blocks = re.findall(r'service\s+(\w+)\s*\{([^}]+)\}', content, re.DOTALL)
            for svc_name, svc_body in service_blocks:
                rpcs = re.findall(r'rpc\s+(\w+)\s*\(', svc_body)
                for rpc in rpcs:
                    if rpc in seen_rpcs:
                        continue

                    call_sites = find_independent_call_sites(
                        self.repo_path, rpc, rel_proto, source_files=source_files
                    )
                    call_files = sorted({cs.file_path for cs in call_sites})
                    if not call_files:
                        continue

                    seen_rpcs.add(rpc)
                    target_symbol = f"{svc_name}.{rpc}"
                    expected_files = [rel_proto] + call_files

                    mutations: dict[str, tuple[str, str]] = {}
                    mutations[rel_proto] = (f"rpc {rpc}(", f"rpc {rpc}V2(")

                    for cs in call_sites:
                        f_path = cs.file_path
                        if f_path in mutations:
                            continue
                        mutation = self._generate_file_mutation(rpc, cs.snippet)
                        if mutation:
                            mutations[f_path] = mutation

                    tasks.append(CrossServiceTask(
                        task_id=f"dyn_task_{svc_name}_{rpc}".lower(),
                        title=f"Refactor {target_symbol} to {svc_name}.{rpc}V2",
                        description=f"Discovered contract {target_symbol} in {rel_proto} with consumers across {len(call_files)} files.",
                        target_symbol=target_symbol,
                        expected_files=expected_files,
                        prompt=f"Rename gRPC method {rpc} to {rpc}V2 in {rel_proto} and all dependent callers and implementations.",
                        sample_mutations=mutations,
                    ))

        # Sort tasks by number of affected files (most impactful first)
        tasks.sort(key=lambda t: len(t.expected_files), reverse=True)
        return tasks[:max_tasks]


